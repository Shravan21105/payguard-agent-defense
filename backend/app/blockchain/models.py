from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class OnChainAuthorizationRequest(BaseModel):
    """Request by an autonomous AI agent to obtain a cryptographically signed authorization."""
    transaction_id: Optional[str] = Field(default=None, description="Optional transaction identifier")
    sender: str = Field(..., description="Initiator agent NEAR account")
    recipient: str = Field(..., description="Target recipient NEAR account")
    amount: float = Field(..., gt=0, description="Amount in NEAR")
    currency: str = Field(default="NEAR", description="Asset currency")
    purpose: str = Field(..., description="Natural language intent/purpose for agent action")
    network_id: str = Field(default="testnet", description="Target NEAR network ('testnet' or 'mainnet')")
    contract_id: Optional[str] = Field(default=None, description="Payguard Vault contract ID")
    timelock_seconds: Optional[int] = Field(default=3600, ge=60, description="Escrow timelock for WARN transactions")


class SignedPolicyAuthorization(BaseModel):
    """Cryptographically signed policy authorization generated by PAYGUARD security daemon."""
    auth_id: str
    sender_id: str
    recipient_id: str
    amount_yocto: str
    amount_near: float
    decision: str
    risk_score: int
    policy_version: str
    nonce: int
    issued_at: int
    expires_at: int
    network_id: str
    contract_id: str
    canonical_payload: str
    signature: str
    signer_public_key: str
    execution_ready: bool
    reasons: List[str]


class OnChainExecutionRequest(BaseModel):
    """Request to submit or record an on-chain vault execution."""
    authorization: SignedPolicyAuthorization
    tx_hash: Optional[str] = Field(default=None, description="NEAR transaction receipt hash if executed via wallet")
    caller_account_id: Optional[str] = Field(default=None, description="Account executing transaction")


class OnChainEscrowActionRequest(BaseModel):
    """Operator decision to release or reject/refund escrowed funds."""
    escrow_id: str
    operator_id: str = Field(default="human_operator_01")
    decision: str = Field(..., description="'APPROVE' (release funds) or 'REJECT' (refund funds)")
    reason: Optional[str] = Field(default="Operator verified transaction")


class OnChainEscrowRecord(BaseModel):
    """Structured record of an on-chain vault escrow."""
    escrow_id: str
    auth_id: str
    sender_id: str
    recipient_id: str
    amount_near: float
    amount_yocto: str
    risk_score: int
    status: str
    created_at: str
    timelock_until: str
    approved_by: Optional[str] = None
    approved_at: Optional[str] = None
    rejection_reason: Optional[str] = None
    tx_hash: Optional[str] = None


class OnChainTransactionRecord(BaseModel):
    """Immutable record of an executed on-chain vault payment."""
    auth_id: str
    tx_hash: str
    sender_id: str
    recipient_id: str
    amount_near: float
    amount_yocto: str
    decision: str
    risk_score: int
    status: str
    block_height: Optional[int] = None
    block_hash: Optional[str] = None
    explorer_url: str
    executed_at: str


class NEARNodeStatus(BaseModel):
    """Diagnostic status of NEAR RPC connection and vault contract."""
    network: str
    rpc_url: str
    status: str
    latest_block_height: int
    latest_block_hash: str
    vault_contract: str
    signer_public_key: str
    is_contract_deployed: bool

