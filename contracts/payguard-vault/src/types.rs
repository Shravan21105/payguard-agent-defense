use near_sdk::json_types::U128;
use near_sdk::{near, AccountId};

#[near(serializers = [json, borsh])]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DecisionType {
    Allow,
    Warn,
    Block,
}

impl DecisionType {
    pub fn as_str(&self) -> &'static str {
        match self {
            DecisionType::Allow => "ALLOW",
            DecisionType::Warn => "WARN",
            DecisionType::Block => "BLOCK",
        }
    }
}

#[near(serializers = [json, borsh])]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EscrowStatus {
    PendingApproval,
    Approved,
    Released,
    Rejected,
    Refunded,
    Expired,
}

impl EscrowStatus {
    pub fn as_str(&self) -> &'static str {
        match self {
            EscrowStatus::PendingApproval => "PENDING_APPROVAL",
            EscrowStatus::Approved => "APPROVED",
            EscrowStatus::Released => "RELEASED",
            EscrowStatus::Rejected => "REJECTED",
            EscrowStatus::Refunded => "REFUNDED",
            EscrowStatus::Expired => "EXPIRED",
        }
    }
}

/// Cryptographically verifiable policy authorization payload generated by PAYGUARD security engine.
#[near(serializers = [json, borsh])]
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PolicyAuthorization {
    pub auth_id: String,
    pub sender_id: AccountId,
    pub recipient_id: AccountId,
    pub amount: U128,
    pub decision: DecisionType,
    pub risk_score: u8,
    pub policy_version: String,
    pub nonce: u64,
    pub issued_at: u64,
    pub expires_at: u64,
    pub network_id: String,
    pub contract_id: AccountId,
}

impl PolicyAuthorization {
    /// Produces domain-separated canonical byte representation for Ed25519 signature verification.
    pub fn to_canonical_bytes(&self) -> Vec<u8> {
        let canonical_str = format!(
            "PAYGUARD:v1:{}:{}:{}:{}:{}:{}:{}:{}:{}:{}:{}:{}",
            self.network_id,
            self.contract_id,
            self.auth_id,
            self.sender_id,
            self.recipient_id,
            self.amount.0,
            self.decision.as_str(),
            self.risk_score,
            self.policy_version,
            self.nonce,
            self.issued_at,
            self.expires_at
        );
        canonical_str.into_bytes()
    }
}

